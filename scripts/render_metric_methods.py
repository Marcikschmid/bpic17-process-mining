"""Measurement methods per quality criterion: values, advantages, limits, use.

Answers 'which algorithms were run per criterion, what was used and why' with
values copied from results/assessment/<name>.json (nothing recomputed) and the
certified HM replay ceiling. Writes results/comparison/metric_methods.{md,tex}.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSESSMENT = ROOT / "results/assessment"
OUT = ROOT / "results/comparison"
MODELS = (("inductive_miner", "IM"), ("heuristics_miner", "HM"), ("refined_imf", "IMf"), ("final_model", "Final"))
# criterion, method, implementation, headline key, advantage, limitation, role in this project
METHODS = (
    ("Fitness", "Token-based replay", "PM4Py fitness_token_based_replay", "token_fitness",
     "fast; local diagnostics (missing/remaining tokens)",
     "non-deterministic with silent transitions; token flooding; invalid with duplicate labels",
     "baseline comparison only"),
    ("Fitness", "Alignment-based", "PM4Py formula; own exact aligner, PM4Py A* cross-check", "alignment_fitness",
     "optimal, deterministic cost; log/model moves as diagnostics",
     "needs finite state space; HM run did not finish",
     "reported fitness value"),
    ("Fitness", "Exact whole-case replay (%)", "own, complete marking graph", "exact_replay_pct",
     "directly 'share of cases represented'",
     "binary per case; bounded nets only",
     "constraint >= 80%"),
    ("Precision", "ETC (token-based)", "PM4Py precision_token_based_replay", "token_precision",
     "fast", "inherits token-replay problems; invalid with duplicate labels", "baseline comparison only"),
    ("Precision", "Align-ET (alignment-based)", "PM4Py formula; own exact finite-state version, PM4Py cross-check",
     "align_et_precision", "prefixes from optimal alignments; deterministic",
     "misleading on non-fitting nets (HM)", "optimisation target"),
    ("Generalization", "Token-based", "PM4Py generalization_tbr", "generalization",
     "standard formula 1 - mean(1/sqrt(n_t))", "counts from token replay; invalid with duplicate labels",
     "baseline comparison only"),
    ("Generalization", "Alignment-based counts", "same formula, counts from optimal alignments", "alignment_generalization",
     "valid with duplicate labels", "heuristic; tie-breaks between equal-cost alignments", "guard rail (max. -0.01)"),
    ("Simplicity", "Arc degree", "PM4Py simplicity_petri_net", "arc_degree_simplicity",
     "normalised (higher = simpler)", "ignores behaviour; flower model scores well", "guard rail (max. -0.05)"),
    ("Simplicity", "Size (nodes)", "own", "nodes", "intuitive", "counts silent routing nodes", "guard rail (max. +25%)"),
    ("Simplicity", "Extended Cardoso", "own (Lassen and van der Aalst 2009)", "extended_cardoso",
     "counts distinct choices per place", "structural only", "reported"),
    ("Simplicity", "Extended Cyclomatic (ECyM)", "own, complete marking graph", "extended_cyclomatic",
     "behavioural complexity of the state space", "bounded nets only", "reported"),
)


def value(record, key, ceiling=None):
    if record.get("token", {}).get("valid") is False and key in ("token_fitness", "token_precision", "generalization"):
        return "invalid"
    found = record["headline"].get(key)
    if found is None:
        return f"<= {ceiling:.2f}" if key == "exact_replay_pct" and ceiling is not None else "n/c"
    if key == "exact_replay_pct":
        return f"{found:.2f}"
    return f"{found:,}" if isinstance(found, int) else f"{found:.3f}"


def main():
    records = {name: json.loads((ASSESSMENT / f"{name}.json").read_text(encoding="utf-8")) for name, _ in MODELS}
    ceiling = json.loads((ROOT / "results/tables/dead_transition_audit.json").read_text(encoding="utf-8"))
    hm_ceiling = ceiling["models"]["heuristics_miner"]["case_replay_upper_bound"]["maximum_fitting_percentage"]
    rows = [(c, m, impl, *(value(records[n], key, hm_ceiling if n == "heuristics_miner" else None) for n, _ in MODELS), adv, lim, role)
            for c, m, impl, key, adv, lim, role in METHODS]
    md = ["# Quality measurement methods (generated by scripts/render_metric_methods.py)", "",
          "Same input for all values: completion projection, 31,509 cases. `invalid` = token replay maps each label "
          "to one transition, not applicable with duplicated labels; `n/c` = not computable (unbounded net or "
          "unfinished alignment); HM token values vary by up to 0.03 between runs (docs/HEURISTICS_SWEEP.md).", "",
          "| Criterion | Method | Implementation | " + " | ".join(label for _, label in MODELS) + " | Advantage | Limitation | Use here |",
          "|" + "---|" * (6 + len(MODELS))]
    md += ["| " + " | ".join(r) + " |" for r in rows]
    (OUT / "metric_methods.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    tex = lambda text: text.replace("_", r"\_").replace("<=", r"$\leq$").replace(">=", r"$\geq$").replace("%", r"\%")
    lines = [r"\begin{tabular}{llrrrrp{0.20\textwidth}p{0.22\textwidth}l}", r"\hline",
             r"Criterion & Method & " + " & ".join(label for _, label in MODELS) + r" & Advantage & Limitation & Use here \\", r"\hline"]
    previous = None
    for r in rows:
        criterion = r[0] if r[0] != previous else ""
        previous = r[0]
        lines.append(" & ".join(tex(x) for x in (criterion, r[1], *r[3:3 + len(MODELS)], *r[3 + len(MODELS):])) + r" \\")
    lines += [r"\hline", r"\end{tabular}"]
    (OUT / "metric_methods.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(md[5:]), flush=True)


if __name__ == "__main__":
    main()
